"""搜索结果过滤：`web_search` 返回的是**网页**，不是商品。

🔴 **为什么要这个模块**（2026-10-19 大宋看到真机卡片效果后提出）：
   `web_search` 搜「京东京东京东 纯奶 价格 评测」返回的前 5 条全是

   ```
   纯奶纯价格报价行情 - 京东
   精选_京东牛奶_国内优惠排行_第203页_什么值得买
   精选_京东牛奶_国内优惠排行_第124页_什么值得买
   盒装纯奶排行 - 京东
   最新国内精选京东奶类制品优惠信息大全_第35页_什么值得买
   ```

   界面上就渲染出 6 张卡片，**全是同一件商品的不同页面**。
   标题还是「京东京东京东」这种博查拼重复前缀的垃圾。

##🔴 为什么规则这么少（两次实测的结论）

   我原本想按「标题含排行/大全/第N页」过滤，**实测发现会误杀**：

   ```
   索尼WH-1000XM5参数配置|详细参数_太平洋产品报价   ← ✅ 是商品页，却含「报价」
   精选_京东牛奶_国内优惠排行_第203页              ← 🔴 是聚合页
   ```

   「报价/价格/排行」这类词在正经商品页里太常见。所以**只挡两类
   「不管它叫什么名字都确定不是商品」的模式**，其余一律放过。

##🔴 实测发现的另一个坑：脏名会被 complete_specs 误解

   喂「盒装纯奶排行 - 京东」给 `complete_specs`，主模型理解成了
   **另一件完全不同的商品**（认养一头牛的儿童奶，125ml×10盒）。

   →所以**过滤必须发生在 complete_specs 之前**，不能等它查完再说。

## 大宋的口径（2026-10-19）

   「**只要脏数据不给用户看就可以**」—— 不追求「数据变干净」，
   只保证「脏的不会出现在用户面前」。所以这个模块**只做减法，不做改写**。
"""

import re

# 🔴 聚合站域名（实测能认出来的就这几个）
#   smzdm = 什么值得买，它的内容是「精选/优惠/排行」聚合，不是商品
_AGG_HOSTS = (
    "smzdm.com",# 什么值得买
    "zonghe.",           # 部分站的「综合」子域
)

# 🔴 标题里的「翻页」标记 —— 这类一定不是单个商品
#   实测样本：「精选_京东牛奶_国内优惠排行_第203页_什么值得买」
#   「_第<数字>页」是聚合列表页的分页标记
_PAGE_MARK = re.compile(r"第\s*\d+\s*页")

# 🔴 站点名重复前缀 —— 博查把搜索词里的站点名前缀拼进了标题
#   实测样本：搜「京东京东京东」→ 标题「京东京东京东京东款奶」
#   判据：同一个 2~4 字片段紧邻重复 3 次以上
_REPEAT_PREFIX = re.compile(r"(.{2,4}?)\1{2,}")

# 🔴 标题尾部的修饰词（**只用于去重，不用于判垃圾**）
#   实测：「索尼WH-1000XM5参数」「索尼WH-1000XM5参数规格」、
#        「..._详细参数」都是同一件商品的不同页面。
_TAIL_NOISE = re.compile(
    r"(参数规格|详细参数|参数配置|技术规格|产品规格|参数|规格|配置"
    r"|性能|功能|价格|报价|图片|视频|评测|怎么样|问答|介绍|详情)+$"
)


def is_junk(name: str, url: str = "") -> bool:
    """判断一条搜索结果是不是「明显不是商品」。**宁可放过，不可错杀。**

    ⚠️ 这个函数**只挡确定是垃圾的**，不判断「是不是一个好商品」——
       后者需要语义理解，不该用正则猜（大宋 2026-10-19口径：
       「只要脏数据不给用户看就可以」）。

    挡掉的只有三类（都是「不管叫什么名字都确定不是商品」）：
      ① 聚合站域名（smzdm）
      ② 标题带「第N页」分页标记
      ③ 站点名前缀重复 3 次以上（博查拼错了）
    """
    title = (name or "").strip()
    if not title:
        return True

    # ① 聚合站
    if any(h in (url or "") for h in _AGG_HOSTS):
        return True

    # ② 分页标记 —— 这是最可靠的信号，实测所有聚合页都带
    if _PAGE_MARK.search(title):
        return True

    # ③ 前缀重复（博查拼重复）
    if _REPEAT_PREFIX.search(title):
        return True

    return False


def clean_results(results: list[dict], max_items: int) -> list[dict]:
    """过滤 + 去重，返回最多 max_items 条。

    🔴 **去重按「去掉站点后缀后的主体名」**：不同搜索词很容易搜到同一件商品的
       不同页面（如「索尼WH-1000XM5参数」和「索尼WH-1000XM5参数_太平洋产品报价」）。

       ⚠️ **注意**：原来的「前18 字」去重基本无效——实测
       「精选_京东牛奶_国内优惠排行_第203页」与「...第124页」
       前 18 字里第203 vs 第124 不同，两个都留下了。
    """
    seen: set[str] = set()
    out: list[dict] = []
    for it in results:
        name = (it.get("name") or "").strip()
        url = (it.get("url") or "").strip()

        if is_junk(name, url):
            continue

        # 🔴 去重键：去掉「_后半段」与「 - 站点名」，再看主体
        key = _dedupe_key(name)
        if key in seen:
            continue
        seen.add(key)

        out.append({"name": name, "url": url,
                    "snippet": (it.get("snippet") or "").strip()})
        if len(out) >= max_items:
            break
    return out


def _dedupe_key(name: str) -> str:
    """算去重键：剥掉站点后缀、分页标记、尾部修饰词，只留主体。

    实测样本（大宋截图那次真机返回）：
      「索尼WH-1000XM5参数_索尼WH-1000XM5参数配置|详细参数_太平洋产品报价」
         → 索尼WH-1000XM5   ← 与下面两条同键
      「索尼WH-1000XM5参数」
         → 索尼WH-1000XM5
      「索尼WH-1000XM5」
         → 索尼WH-1000XM5
    三条同键 → 只留 1 条。

    🔴 **为什么必须剥掉尾部修饰词**（实测踩到，第一版漏了）：
       「索尼WH-1000XM5参数」与「索尼WH-1000XM5」是同一件商品的两个页面，
       不剥的话用户会看到两张几乎一样的卡。
    """
    key = name
    # 去掉「_后半段」与「 - 站点名」
    for sep in (" - ", "_", " | ", "|"):
        if sep in key:
            key = key.split(sep)[0]
    # 去掉「第N页」
    key = _PAGE_MARK.sub("", key)

    # 🔴 **反复剥**尾部修饰词（可能叠多个：参数_详细参数_规格_性能_功能）。
    #   用 while 是因为「参数规格」剥掉「规格」后末尾又露出「参数」。
    #   上限 4 轮，纯防正则意外死循环。
    for _ in range(4):
        stripped = _TAIL_NOISE.sub("", key).strip(" -_|")
        if stripped == key or not stripped:
            break
        key = stripped

    # 去掉空格后比对（用户输入常带空格差异）
    return key.replace(" ", "").lower()